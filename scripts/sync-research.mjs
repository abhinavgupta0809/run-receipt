// Rebuilds data/research.json from the reviews dashboard's own data files, so the case study and the dashboard
// can never show different figures. Run: node scripts/sync-research.mjs [path to perplexity-reviews/site/data]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import os from "node:os";

const src = process.argv[2] ?? path.join(os.homedir(), "Desktop/Projects/perplexity-reviews/site/data");
const read = (f) => JSON.parse(readFileSync(path.join(src, f), "utf8"));
const summary = read("summary.json"), insights = read("insights.json"), reviews = read("reviews.json");
const rows = reviews.rows.map((r) => Object.fromEntries(reviews.columns.map((c, i) => [c, r[i]])));
const byId = new Map(rows.map((r) => [r.review_id, r]));
const month = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const day = (iso) => { const [y, m, d] = iso.slice(0, 10).split("-").map(Number); return `${month[m - 1]} ${d}, ${y}`; };
const cluster = (list, id) => {
  const x = list.find((e) => e.id === id);
  if (!x) throw new Error(`cluster ${id} is not in insights.json`);
  const s = x.scopes.all.stats;
  return { title: x.scopes.all.title, reviews: s.count, lowStar: s.low_star_count, android: s.android_count, ios: s.ios_count };
};
// Quotes are picked by review id. Each excerpt must appear word for word in the stored review, or the sync fails.
const PICKS = [
  { id: "ios_14429214385", tone: "cost", excerpt: "because you don’t get an estimate it’s hard for budgeting." },
  { id: "ios_14443708097", tone: "cost", excerpt: "It uses up credits fast with no way to stop prompts after they start" },
  { id: "ios_14375268685", tone: "cost", excerpt: "search forces you to use computer then computer drains your credits on simple task" },
  { id: "ios_14519831597", tone: "cost", excerpt: "I installed max for 20 minutes and asked it to review a bug and check logs. 1300 credits later, it did neither." },
];
const quotes = PICKS.map((p) => {
  const r = byId.get(p.id);
  if (!r) throw new Error(`review ${p.id} is not in reviews.json`);
  if (!r.review_text.includes(p.excerpt)) throw new Error(`excerpt for ${p.id} is not word for word in the review`);
  return { tone: p.tone, text: p.excerpt, stars: r.rating, when: day(r.date_utc), source: `${r.platform === "ios" ? "App Store" : "Google Play"} review, app v${r.app_version}`, reviewId: r.review_id };
});
const all = summary.all.stats, meta = summary.meta;
const money = insights.callouts.find((c) => c.id === "c_money").scopes.all.stats;
const out = {
  note: "Generated by scripts/sync-research.mjs from the reviews dashboard data (perplexity-reviews/site/data). Do not edit by hand. Quotes are verbatim excerpts, checked against the stored review on every sync. Dates are UTC.",
  generated: day(meta.generated_at),
  dashboardUrl: "https://perplexity-reviews-site.vercel.app/",
  corpus: { reviews: all.count, android: all.android_count, ios: all.ios_count, from: day(meta.date_range.start), to: day(meta.date_range.end), substantive: all.substantive, stores: "Google Play and App Store" },
  labelCheck: { matches: meta.gold.primary_label.matches, n: meta.gold.primary_label.n },
  money: { reviews: money.count, lowStar: money.low_star_count },
  creditsRunOut: cluster(insights.improvements, "i_credits"),
  computerCredits: cluster(insights.improvements, "i_computer"),
  larger: [cluster(insights.improvements, "i_free_questions"), cluster(insights.improvements, "i_wrong")],
  // The first read, on Oct 2, 2026, before the dashboard existed. Kept for the "How I got to this problem" steps.
  firstRead: { reviews: 500, problemStatements: 6 },
  quotes,
};
writeFileSync(path.join(process.cwd(), "data", "research.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`research.json: ${out.corpus.reviews} reviews, ${quotes.length} quotes, generated ${out.generated}`);
